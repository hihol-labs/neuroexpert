/**
 * Задел под кейсы (G-013, CURRENT_PLAN B1). Кейс = двухточечное доказательство:
 * одна метрика, замеренная тем же промпт-корпусом ДО и ПОСЛЕ внедрения.
 * Пока внедрений нет — массив пуст, страница примера показывает честное
 * пустое состояние без цифр (запрет overclaim 2026-04-19/20).
 */
export interface CaseStudy {
  /** Пара «ниша × город», например «Стоматология × Тюмень». */
  pair: string;
  /** Период между замерами, например «2 недели после публикаций». */
  period: string;
  /** Что измеряли, например «упоминаний клиники в ответах на 10 вопросов». */
  metric: string;
  /** Значение ДО (число или текст вроде «0 из 10»). */
  before: string;
  /** Значение ПОСЛЕ тем же корпусом. */
  after: string;
  /** Источник: даты замеров, платформы, ссылка на отчёты. */
  source: string;
  /** Честная пометка формата (что не входило, ограничения). */
  note?: string;
}

export const CASES: CaseStudy[] = [];
